def indonesian_surah_name(surah_id: int, api_name: str | None = None) -> str:
    if api_name and _looks_indonesian(api_name):
        return api_name
    return SURAH_NAME_ID.get(surah_id, api_name or f"Surat {surah_id}")


def _looks_indonesian(name: str) -> bool:
    lower = name.lower()
    if any(
        x in lower
        for x in (
            "an-",
            "at-",
            "ash-",
            "ar-",
            "al-",
            "the ",
            "chapter",
        )
    ):
        return False
    return True
